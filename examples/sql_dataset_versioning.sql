-- Dataset versioning: each CREATE DATASET AS TABLE captures a point-in-time snapshot.



CREATE TABLE src (id INT, a INT, b TEXT, c TEXT, d TEXT);

INSERT INTO src BULK 20 START 1 STEP 1;



CREATE DATASET snap AS TABLE src;

DELETE FROM src;

INSERT INTO src BULK 10 START 1 STEP 1;

CREATE DATASET snap AS TABLE src;



CREATE TABLE v1 (id INT, a INT, b TEXT, c TEXT, d TEXT);

CREATE TABLE v2 (id INT, a INT, b TEXT, c TEXT, d TEXT);

LOAD DATASET snap VERSION 1 INTO v1;

LOAD DATASET snap VERSION 2 INTO v2;



SELECT id FROM v1 ORDER BY id ASC LIMIT 10;

SELECT id FROM v2 ORDER BY id ASC LIMIT 10;



DROP DATASET snap;

DROP TABLE IF EXISTS v2;

DROP TABLE IF EXISTS v1;

DROP TABLE IF EXISTS src;

